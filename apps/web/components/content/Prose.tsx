import { CircleCheck, Info, TriangleAlert } from 'lucide-react'
import Image from 'next/image'
import type { ReactNode } from 'react'
import { FACT_BLOCK } from '@/content/registry'

/** The reusable "About QRfinity" fact block, word for word everywhere. */
export function FactBlock() {
  return (
    <aside aria-label="About QRfinity" className="my-8 rounded-lg bg-mint p-4 text-ink md:p-6">
      <p className="max-w-[72ch]">{FACT_BLOCK}</p>
    </aside>
  )
}

/** "Static or dynamic?" recommendation box used on use-case pages. */
export function Recommendation({
  pick,
  children,
}: {
  pick: 'static' | 'dynamic' | 'either'
  children: ReactNode
}) {
  const label =
    pick === 'static'
      ? 'We recommend: static'
      : pick === 'dynamic'
        ? 'We recommend: dynamic'
        : 'Either works'
  return (
    <div className="my-6 rounded-lg border-[1.5px] border-evergreen bg-surface p-4 md:p-6">
      <p className="label mb-2 inline-flex items-center gap-1.5 rounded-pill bg-evergreen px-3 py-1 font-bold text-on-evergreen">
        <CircleCheck aria-hidden="true" size={16} strokeWidth={1.75} />
        {label}
      </p>
      <div className="text-ink [&>p:last-child]:mb-0">{children}</div>
    </div>
  )
}

export function Callout({
  tone = 'info',
  children,
}: {
  tone?: 'info' | 'warning'
  children: ReactNode
}) {
  const Icon = tone === 'warning' ? TriangleAlert : Info
  return (
    <div
      className={`my-6 flex gap-3 rounded-lg p-4 text-ink ${tone === 'warning' ? 'border-[1.5px] border-scan-fail bg-surface' : 'bg-surface-sunk'}`}
    >
      <Icon aria-hidden="true" size={20} strokeWidth={1.75} className="mt-[3px] shrink-0" />
      <div className="[&>p:last-child]:mb-0">{children}</div>
    </div>
  )
}

/** A screenshot of QRfinity itself, generated by scripts/screenshots.mjs into public/screens/. */
export function Screenshot({ name, alt }: { name: string; alt: string }) {
  return (
    <figure className="my-6 overflow-hidden rounded-lg border border-hairline bg-surface">
      <Image
        src={`/screens/${name}.jpg`}
        alt={alt}
        width={1280}
        height={800}
        sizes="(min-width: 768px) 720px, 100vw"
        className="h-auto w-full"
      />
    </figure>
  )
}
